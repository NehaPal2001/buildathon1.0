const EMPTY_EXCLUSIONS = `${EXCLUSIONS_HEADING}

<!-- Hand-written. Recon never rewrites this section. Three forms are recognised: -->
<!-- ignore states from <glob> -->
<!-- ignore states whose origin is <free text> -->
<!-- treat <path> as always in regression scope -->
`;

function ranked(counts: Record<string, number>): string {
  const rows = Object.entries(counts).sort((a, b) => b[1] - a[1]);
  if (!rows.length) return '_none found_\n';
  return ['| method | uses |', '|---|---|', ...rows.map(([k, v]) => `| ${k} | ${v} |`)].join('\n') + '\n';
}

function obtainSample(suite: Suite): string {
  const keys = Object.keys(suite.fixtureKeys);
  switch (suite.obtainPattern) {
    case 'test.extend':
      return `Page objects are fixtures declared with \`test.extend\` in \`${suite.fixtureFile}\`. A test destructures them:

\`\`\`ts
import { test, expect } from '../fixtures';

test('…', async ({ ${keys.slice(0, 2).join(', ')} }) => {
  await ${keys[0]}.goto();
});
\`\`\`

Fixture keys: ${keys.map((k) => `\`${k}\` → \`${suite.fixtureKeys[k]}\``).join(', ')}.`;
    case 'constructor':
      return 'Page objects are constructed inline: `const p = new XPage(page)`.';
    case 'helper':
      return 'Page objects come from a helper function.';
    default:
      return 'No page-object pattern detected.';
  }
}

export function renderConventions(suite: Suite): string {
  const poDir = suite.pageObjects.length ? path.posix.dirname(suite.pageObjects[0].file) + '/' : '(none)';
  const specDirs = [...new Set(suite.specs.map((s) => path.posix.dirname(s.path)))].join(', ');
  const titles = suite.titleSamples.map((t) => `- ${t}`).join('\n');
  const poList = suite.pageObjects.map((p) => `- \`${p.className}\` (${p.file}): ${p.methods.map((m) => `\`${m}()\``).join(', ')}`).join('\n');
  return `# Suite conventions

_Generated by Recon from \`${suite.suiteDir}/\` on branch \`${suite.branch}\`. Everything above the Exclusions heading is regenerated on each run._

## Page objects

Location: \`${poDir}\`, one \`export class XPage\` per file, constructor takes \`page\`.

${obtainSample(suite)}

${poList}

## Locators (ranked by use)

${ranked(suite.locatorCounts)}
Generated specs use the top-ranked strategy first and never inline a locator in a spec file — locators live in page objects.

${suite.inlineLocatorCalls} locator call(s) are made directly on \`page\` inside spec files, for shared page chrome that has no page object. That is the suite's documented exception, not a pattern to copy: generated specs must still go through page objects.

## Assertions (ranked by use)

${ranked(suite.assertionCounts)}
## Files and naming

Specs live in \`${specDirs}\`, named \`<name>.spec.ts\`. Titles are plain sentences inside one \`test.describe\` per file, for example:

${titles}

## Setup and auth

Pattern: \`${suite.setupPattern}\`.

`;
}

/** A fenced-code opener: which character (`` ` `` or `~`) and how many of them. */
interface Fence {
  char: '`' | '~';
  len: number;
}

/** First non-whitespace run of 3+ backticks or tildes at the start of a line, if any. */
function fenceOpener(line: string): Fence | null {
  const m = line.match(/^\s*(`{3,}|~{3,})/);
  if (!m) return null;
  return { char: m[1][0] as '`' | '~', len: m[1].length };
}

/**
 * A closing fence must use the SAME character as the opener and at least as many of them, with
 * nothing else on the line but surrounding whitespace (CommonMark's actual rule) — a `~~~` line
 * inside a ``` fence (or vice versa) must not close it, and a fence opened with 3 backticks can
 * be closed by 4+.
 */
function isFenceCloser(line: string, fence: Fence): boolean {
  const re = fence.char === '`' ? /^\s*`{3,}\s*$/ : /^\s*~{3,}\s*$/;
  if (!re.test(line)) return false;
  const run = line.match(fence.char === '`' ? /`+/ : /~+/)![0];
  return run.length >= fence.len;
}

/**
 * Byte offset of the start of a `## Exclusions` heading line, or -1 if none exists at all.
 *
 * When `respectFences` is true, a heading inside a fenced code block (tracked with correct
 * open/close delimiter matching, per `fenceOpener`/`isFenceCloser`) is skipped, on the theory
 * that a worked example in the generated portion could legitimately show the heading without
 * meaning it. When false, fence state is ignored entirely and the first line that reads exactly
 * `## Exclusions` wins, fenced or not.
 */
function findHeadingLine(text: string, respectFences: boolean): number {
  let offset = 0;
  let fence: Fence | null = null;
  // Keep each line's own trailing newline attached, so offsets sum back to the original text.
  for (const rawLine of text.split(/(?<=\n)/)) {
    const line = rawLine.replace(/[\r\n]+$/, '');
    if (respectFences) {
      if (fence) {
        if (isFenceCloser(line, fence)) fence = null;
        offset += rawLine.length;
        continue;
      }
      const opener = fenceOpener(line);
      if (opener) {
        fence = opener;
        offset += rawLine.length;
        continue;
      }
    }
    if (line.replace(/\s+$/, '') === EXCLUSIONS_HEADING) return offset;
    offset += rawLine.length;
  }
  return -1;
}

/**
 * Byte offset of the start of the real `## Exclusions` heading line, or -1 if none exists.
 *
 * The stakes here are asymmetric: losing a tester's hand-written Exclusions section is a
 * serious data-loss bug (it's the only feedback mechanism this tool has), whereas anchoring on
 * a heading that turns out to have been inside a code fence just means the tester briefly sees
 * a spurious duplicate heading and fixes it. So this is two-pass and always prefers preserving
 * content over being precise about fence boundaries:
 *
 *  1. Scan with correct fence tracking (matching delimiter character and length, so a `~~~`
 *     line inside a ``` block — or an unterminated fence anywhere earlier in the document —
 *     can't desync the parser). If an unfenced heading is found this way, use it.
 *  2. Otherwise, re-scan ignoring fence state entirely. If the heading text exists anywhere as
 *     its own line, use that — even though it may in fact sit inside what looks like a fence.
 *  3. Only if the heading appears nowhere at all does the caller fall back to the empty
 *     scaffold.
 *
 * This function does NOT guarantee it always finds the "intended" heading when the document is
 * pathological (e.g. a heading only ever appears inside a fence, and that really is what the
 * tester meant to write as a plain heading with an unbalanced fence above it). What it does
 * guarantee is that content is never silently dropped: whichever pass succeeds, everything from
 * the returned offset onward is exactly what `mergeConventions` preserves.
 */
function findExclusionsIndex(text: string): number {
  const strict = findHeadingLine(text, true);
  if (strict >= 0) return strict;
  return findHeadingLine(text, false);
}

export function mergeConventions(existing: string | null, generated: string): string {
  const idx = existing !== null ? findExclusionsIndex(existing) : -1;
  const exclusions = idx >= 0 ? existing!.slice(idx) : EMPTY_EXCLUSIONS;
  const merged = generated + exclusions;
  // Invariant, asserted directly rather than trusted: whatever we decided the Exclusions tail
  // is must appear intact in the output. True by construction today (merged is literally
  // `generated + exclusions`) — this exists so a future refactor that breaks the slice/concat
  // fails loudly instead of silently shipping a truncated Exclusions section.
  if (idx >= 0 && !merged.endsWith(exclusions)) {
    throw new Error('mergeConventions: computed Exclusions tail did not survive into the merged output');
  }
  return merged;
}

export function writeConventions(suite: Suite, outFile: string): void {
  const existing = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : null;
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, mergeConventions(existing, renderConventions(suite)));
}

const USAGE = 'usage: conventions.ts --suite <suite.json> --out <conventions.md>';

if (isMain(__filename)) {
  const args = parseArgs(process.argv.slice(2));
  if (wantsHelp(args)) printUsage(USAGE);
  if (!args.suite || !args.out) fail(USAGE);
  try {
    writeConventions(SuiteSchema.parse(readJson(args.suite)), args.out);
  } catch (err) {
    fail(formatError(err));
  }
}
